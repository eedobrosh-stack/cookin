"""Generate pawed_i18n_x.py from i18n_x/<lang>.json (translator output). Run: python3 build_i18n_x.py"""
import json, os
LANGS = ("ja", "zh", "ko", "sv", "no", "fi")
D = os.path.join(os.path.dirname(os.path.abspath(__file__)), "i18n_x")
src = json.load(open(os.path.join(D, "source.json"), encoding="utf-8"))
out = {}
for l in LANGS:
    fp = os.path.join(D, l + ".json")
    if not os.path.exists(fp):
        print("missing", l); continue
    d = json.load(open(fp, encoding="utf-8"))
    assert set(d["T"]) == set(src["T"]), (l, "T keys")
    assert len(d["P"]) == len(src["P"]) and len(d["USER"]) == 8 and len(d["COOKIE"]) == 4 and set(d["CHARTS"]) == set(src["CHARTS_EN"]), l
    out[l] = d
with open(os.path.join(os.path.dirname(D), "pawed_i18n_x.py"), "w", encoding="utf-8") as f:
    f.write('"""GENERATED by build_i18n_x.py from i18n_x/*.json: UI translations for ja, zh (Traditional), ko, sv, no, fi."""\nTX = ')
    f.write(json.dumps(out, ensure_ascii=False, indent=0))
    f.write("\n")
print("wrote", sorted(out))
